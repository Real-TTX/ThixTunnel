using System.Text;
using ThixTunnel.Core.Models;

namespace ThixTunnel.Core.Infrastructure;

/// <summary>
/// Writes the ssh configuration of one connection attempt.
/// ssh passes "-F" on to the jump hosts it starts for "-J", but not "-o" options; so everything that has to apply
/// to every hop (BatchMode, keep-alive, host key policy) lives in this file and not on the command line.
/// </summary>
internal static class SshConfigWriter
{
    public const string HostAliasPrefix = "thixhop";

    /// <summary>Only for the end-to-end tests: a known_hosts file of their own instead of the user's.</summary>
    internal static string? KnownHostsFileForTests { get; set; }

    public static string HostAlias(int hopIndex) => $"{HostAliasPrefix}{hopIndex + 1}";

    public static string FileName(Guid routeId) => $"route-{routeId:N}.conf";

    /// <summary>Builds the configuration text. <paramref name="interactive"/> allows prompts (password, unknown host key).</summary>
    public static string Build(IReadOnlyList<SshProfile> hops, bool interactive)
    {
        var text = new StringBuilder();
        text.AppendLine("# Generated by ThixTunnel for one connection. Changes are overwritten.");

        for (var index = 0; index < hops.Count; index++)
        {
            AppendHost(text, HostAlias(index), hops[index]);
        }

        text.AppendLine("Host *");
        text.AppendLine($"    BatchMode {(interactive ? "no" : "yes")}");
        // Unknown host keys may be confirmed by the user in an interactive attempt, never automatically.
        // A changed host key is always refused by ssh, whatever this option says.
        text.AppendLine($"    StrictHostKeyChecking {(interactive ? "ask" : "yes")}");
        text.AppendLine("    ExitOnForwardFailure yes");
        text.AppendLine("    ServerAliveInterval 15");
        text.AppendLine("    ServerAliveCountMax 3");
        text.AppendLine("    ConnectTimeout 15");
        text.AppendLine("    LogLevel ERROR");
        if (KnownHostsFileForTests is not null)
        {
            text.AppendLine($"    UserKnownHostsFile \"{KnownHostsFileForTests.Replace('\\', '/')}\"");
        }

        return text.ToString();
    }

    /// <summary>Writes the file and returns its name (relative to <see cref="AppPaths.SshConfigDirectory"/>).</summary>
    /// <remarks>
    /// ssh hands "-F" to the jump hosts without quotes; a relative file name (ssh runs in the folder) avoids
    /// trouble with spaces in the user's profile path.
    /// </remarks>
    public static string Write(Guid routeId, IReadOnlyList<SshProfile> hops, bool interactive)
    {
        Directory.CreateDirectory(AppPaths.SshConfigDirectory);
        var fileName = FileName(routeId);
        File.WriteAllText(Path.Combine(AppPaths.SshConfigDirectory, fileName), Build(hops, interactive), new UTF8Encoding(false));
        return fileName;
    }

    public static void Delete(Guid routeId)
    {
        try
        {
            File.Delete(Path.Combine(AppPaths.SshConfigDirectory, FileName(routeId)));
        }
        catch (IOException)
        {
            // still in use by a closing ssh process; overwritten next time
        }
    }

    private static void AppendHost(StringBuilder text, string alias, SshProfile profile)
    {
        text.AppendLine($"Host {alias}");
        text.AppendLine($"    HostName {profile.HostName}");
        text.AppendLine($"    Port {profile.Port}");
        text.AppendLine($"    User {profile.UserName}");

        switch (profile.AuthenticationMethod)
        {
            case SshAuthenticationMethod.KeyFile:
                // Forward slashes: no escaping rules of ssh_config apply to them, and Windows OpenSSH accepts them.
                text.AppendLine($"    IdentityFile \"{profile.KeyFilePath.Replace('\\', '/')}\"");
                text.AppendLine("    IdentitiesOnly yes");
                text.AppendLine("    PreferredAuthentications publickey");
                break;
            case SshAuthenticationMethod.Password:
                text.AppendLine("    PreferredAuthentications keyboard-interactive,password");
                text.AppendLine("    PubkeyAuthentication no");
                break;
            default:
                text.AppendLine("    PreferredAuthentications publickey");
                break;
        }

        text.AppendLine();
    }
}
